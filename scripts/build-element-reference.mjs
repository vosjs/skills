#!/usr/bin/env node
// Writes skills/vos-port/references/elements-and-context.md: the element,
// context, timeline and ease declarations as the PUBLISHED @vosjs packages
// ship them, so a port reads the types here instead of digging through
// node_modules. The declarations are copied verbatim with their doc comments;
// only the notes between them are written by hand (below).
//
//   node scripts/build-element-reference.mjs           # regenerate from npm latest
//   node scripts/build-element-reference.mjs --check   # exit 1 if the page is stale
//   node scripts/build-element-reference.mjs --core <dir> --timeline <dir>
//                                                      # from local package dirs
//
// Needs npm and tar on PATH (and the network unless both dirs are given).
import { execFileSync } from 'node:child_process'
import { existsSync, mkdtempSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'

const root = resolve(dirname(new URL(import.meta.url).pathname), '..')
const OUT = join(root, 'skills/vos-port/references/elements-and-context.md')
const args = process.argv.slice(2)
const check = args.includes('--check')
const argDir = (flag) => {
  const i = args.indexOf(flag)
  return i === -1 ? null : resolve(args[i + 1])
}

function packageDir(name, local) {
  if (local) return local
  const dir = mkdtempSync(join(tmpdir(), 'vos-ref-'))
  const file = execFileSync('npm', ['pack', `${name}@latest`, '--silent', '--pack-destination', dir], {
    encoding: 'utf8',
  }).trim().split('\n').pop()
  execFileSync('tar', ['-xzf', join(dir, file), '-C', dir])
  return join(dir, 'package')
}

function declarations(pkgDir, marker) {
  const dist = join(pkgDir, 'dist')
  for (const f of readdirSync(dist).filter((f) => f.endsWith('.d.ts'))) {
    const text = readFileSync(join(dist, f), 'utf8')
    if (text.includes(marker)) return text
  }
  throw new Error(`${pkgDir}: no .d.ts declares ${marker}`)
}

// One declaration by name, with the doc comment directly above it.
function extract(text, name) {
  const lines = text.split('\n')
  const start = lines.findIndex((l) =>
    new RegExp(`^(declare )?(interface|type|function|const) ${name}\\b`).test(l),
  )
  if (start === -1) throw new Error(`declaration ${name} not found`)
  let from = start
  if (lines[start - 1]?.trim() === '*/') {
    while (from > 0 && !lines[from - 1].trim().startsWith('/**')) from--
    from--
  }
  let end = start
  let depth = 0
  for (let i = start; i < lines.length; i++) {
    for (const ch of lines[i]) {
      if (ch === '{' || ch === '(') depth++
      if (ch === '}' || ch === ')') depth--
    }
    end = i
    if (depth <= 0 && /[;}]\s*$/.test(lines[i])) break
  }
  return lines
    .slice(from, end + 1)
    .join('\n')
    .replace(/^declare /gm, '')
}

const coreDir = packageDir('@vosjs/core', argDir('--core'))
const timelineDir = packageDir('@vosjs/timeline', argDir('--timeline'))
const elementsDir = packageDir('@vosjs/elements', argDir('--elements'))
const sharedDir = packageDir('@vosjs/shared', argDir('--shared'))
const version = (dir) => JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8')).version
const core = declarations(coreDir, 'interface VosContext')
const timeline = declarations(timelineDir, 'type EaseName')
const shared = declarations(sharedDir, 'interface ParamSpec')

// The largest texture a raster assumes when the GPU does not say, read from
// the runtime so the ceiling on the page is the one the engine uses.
const maxTexture = /DEFAULT_MAX_TEXTURE_SIZE = (\d+)/.exec(
  readFileSync(join(elementsDir, 'dist/index.js'), 'utf8'),
)
if (!maxTexture) throw new Error('@vosjs/elements: DEFAULT_MAX_TEXTURE_SIZE not found')
const MAX_TEXTURE = Number(maxTexture[1])

// The props an element's proxy re-rasters on, read from the runtime itself:
// the declarations have lagged it, and this list is what a write does.
const elementsJs = readFileSync(join(elementsDir, 'dist/index.js'), 'utf8')
const rasterSet = /RASTER_PROPS = [^[]*\[([^\]]*)\]/.exec(elementsJs)
if (!rasterSet) throw new Error('@vosjs/elements: RASTER_PROPS not found')
const rasterProps = [...rasterSet[1].matchAll(/"([A-Za-z]+)"/g)].map((m) => `\`${m[1]}\``)

const block = (text, names) => '```ts\n' + names.map((n) => extract(text, n)).join('\n\n') + '\n```'

const page = `<!-- Generated by scripts/build-element-reference.mjs from @vosjs/core ${version(coreDir)}, @vosjs/elements ${version(elementsDir)}, @vosjs/timeline ${version(timelineDir)} and @vosjs/shared ${version(sharedDir)}. Do not edit by hand: re-run the script. -->

# Elements, the context and eases: the declarations

What a program's config and functions accept, copied from the published
type declarations so a port never has to read \`node_modules\`. The notes
between the blocks are the facts the declarations do not say; the units
are in SKILL.md's "coordinates, measured" and the draw order in its
"Layering".

## The config

A \`config.json\` is this shape, functions as strings. \`elements\` is typed
loosely here; its members are the element types below.

${block(core, ['FontFaceDecl', 'VosConfigJson'])}

## Elements (\`config.elements[]\`)

\`content\`, \`font.family\` and \`font.color\` of a text element are the three
fields that take a \`{ "$data": "<key>" }\` binding, and the only ones that
re-resolve on a data edit; every other field is read once at build. The key
names a TOP-LEVEL key of \`config.data\` (no dotted path, no array index), so
a list of words that each need binding is one key per word; \`content\`
takes the value as a string. A bound \`split\` element follows a data edit
too: its units are rebuilt from the new words and the timeline is rebuilt
over them (\`@vosjs/elements\` 0.9.0 with core 0.25.3; before that the
studio reloaded the program for such a knob and other hosts kept the old
word). So a per-letter word that is a knob is ONE bound \`split\` element,
never a pool of per-letter elements written from \`onFrame\`: a person can
retype a bound element in the studio, and cannot retype a pool.
\`font.size\`, \`letterSpacing\`, \`transform.translateX/Y\`, \`stroke.width\`
and \`shadow.blur\` are design pixels (a 1080-high frame). There is no
\`mask\`, \`clip\`, \`blend\` or group field on any element: SKILL.md's
"honest gaps" says what to do instead.

${block(core, [
  'DataRef',
  'BaseElement',
  'ElementPosition',
  'PositionPreset',
  'Anchor',
  'Transform',
  'TextElement',
  'ImageElement',
  'SVGElement',
  'VideoElement',
  'AudioElement',
])}

## An element at runtime (\`ctx.elements.get(id)\`)

What \`createTimeline\` and \`onFrame\` animate: \`el.props\` (and
\`el.segments[i]\` under \`split\`). \`props.x\` / \`props.y\` are RENDER pixels
from the frame centre with \`y\` down, and \`rotation\` is degrees
counter-clockwise, unlike the config's design-pixel \`transform\`.

Writing any of ${rasterProps.join(', ')} on a text element's \`props\`
re-rasters it (the runtime's own list), so a scramble or a counter writes
\`el.props.content\` in \`onFrame\` and a colour change sets \`el.props.color\`.
The tween dialect animates numbers only: tween \`fontSize\` and
\`letterSpacing\`, SET the strings. \`props.zIndex\` is settable too.

Every such write queues a re-raster, even of an unchanged value, so guard
a per-frame write: \`if (el.props.content !== next) el.props.content = next\`.
These writes do nothing on a \`split\` element (its units are structure):
change a split element's words through its binding, never its props.

A text raster never fails for being long: its density drops until the
longest side fits the GPU's largest texture (${MAX_TEXTURE} px when the GPU does
not say), so a line past about ${MAX_TEXTURE} design px at 1080p, or half that at
2160p, renders softer. Only then is a long marquee worth cutting into
elements, and each piece stays bound.

${block(core, ['ElementProps', 'ElementInstance'])}

## Knobs (\`config.params\` and \`config.presets\`)

A knob is a \`ParamSpec\` over one top-level \`data\` key, and a Look a named
set of values. vos.so keeps at most 12 knobs and 8 Looks, the first valid
ones, and \`vos check\` names every one it would drop before a push. Every
bound word stays a \`data\` key whether or not it has a knob: the studio's
element panel retypes a bound element directly, so the 12 knobs go to what
a person reaches for first (the palette, the headline), not to every word.
A \`text\` knob with \`multiline: true\` suits a list a painter draws line by
line; a list of elements is one key per element.

${block(shared, ['ParamValue', 'ParamSpec', 'LookPreset', 'TEXT_PARAM_MAX'])}

## The context (\`ctx\`)

\`setup(ctx)\` gets a \`SetupContext\` and may return assets;
\`createContent(ctx, setupData)\` returns a \`ContentResult\`;
\`createTimeline(ctx, content, duration)\` returns the timeline;
\`onFrame(ctx, content, deltaTime)\` runs every frame, \`ctx.time\` being the
program's time in seconds. \`ctx.data\` is read-only: a knob changes it from outside,
and \`onFrame\` reads the new value on the next frame. Read \`ctx.data\` on
every frame, never a copy taken in \`createContent\`.

${block(core, ['Resolution', 'LoadersRegistry', 'UtilsRegistry', 'SetupContext', 'VosContext', 'ContentResult'])}

## The timeline (what \`createTimeline\` returns)

Author it as GSAP: \`const tl = ctx.gsap.timeline({ paused: true })\`, tweens
on \`el.props\`, \`tl.addLabel(name, t)\` per scene, return \`tl\`. This is the
whole surface the engine calls on it.

${block(core, ['VosTimeline'])}

## Eases

An \`ease\` string anywhere GSAP takes one. Beyond the names below the
engine accepts the parameterized forms \`back.out(1.7)\`,
\`elastic.out(1, 0.3)\`, \`steps(5)\`, and \`css-bezier(x1, y1, x2, y2)\`,
which is CSS's \`cubic-bezier\` and Remotion's \`Easing.bezier\` with the same
four numbers (\`cubic-bezier\` itself is not a name). A bare family
(\`'power2'\`) means \`.out\`. **An unknown name is not an error: it plays
linear.** \`vos check\` warns \`unknown-ease\` for a literal \`ease: '…'\` it
cannot resolve; through \`@vosjs/core\` 0.25.0 that warning also fired on
\`css-bezier\`, wrongly, so ignore it there. An ease held in a variable is
not checked: the side-by-side is where it shows.

${block(timeline, ['EaseFamily', 'EaseDirection', 'EaseName', 'resolveEase'])}
`

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  if (current !== page) {
    console.error(`${OUT} is stale: run node scripts/build-element-reference.mjs`)
    process.exit(1)
  }
  console.log('elements-and-context.md is current')
} else {
  writeFileSync(OUT, page)
  console.log(`wrote ${OUT} (${page.split('\n').length} lines)`)
}
